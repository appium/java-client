package io.appium.java_client.android;

/** Emulated GSM signal strength levels. */
public enum GsmSignalStrength {
    /** No signal or unknown strength. */
    NONE_OR_UNKNOWN,
    /** Poor signal. */
    POOR,
    /** Moderate signal. */
    MODERATE,
    /** Good signal. */
    GOOD,
    /** Great signal. */
    GREAT
}
