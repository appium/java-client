package io.appium.java_client.android;

/** Actions that can be performed on an emulated GSM call. */
public enum GsmCallActions {
    /** Initiates a call. */
    CALL,
    /** Accepts an incoming call. */
    ACCEPT,
    /** Cancels the call. */
    CANCEL,
    /** Puts the call on hold. */
    HOLD
}
